/**
 * 「webhook 地址还没生成」这句话的措辞。
 *
 * 和 scheduler.ts 是同一类问题，同一个理由：
 * 拖一个「Webhook 触发」节点上画布，用户就合理地相信"外部现在能触发它了" ——
 * 但地址不是配置出来的，得先生成一次才存在。在此之前这个节点**什么都不会发生**，
 * 而画布上看不出任何区别。
 *
 * 这个项目里最严重的失败模式一直是这一类：静默地不干活，而且看起来一切正常。
 *
 * 状态本身在 store 里（`webhookReady`），因为画布节点要跟着它重渲染；
 * 而且它是**三态**的：null 表示还没探到结果，那时候一个字都不该说。
 */

